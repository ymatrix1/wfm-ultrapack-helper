#!/usr/bin/env python3
"""Generate src/pkg_keys.h from a rsa_keys.py holding the public LibOrbisPkg test keysets.

usage: gen_pkg_keys.py path/to/rsa_keys.py > src/pkg_keys.h
rsa_keys.py defines FakeKeyset and PkgDerivedKey3Keyset (dicts of bytes) copied from
LibOrbisPkg Util/Keys.cs.
"""
import sys, runpy

ns = runpy.run_path(sys.argv[1])
FIELDS = [('n', 'Modulus', 256), ('p', 'Prime1', 128), ('q', 'Prime2', 128),
          ('dp', 'Exponent1', 128), ('dq', 'Exponent2', 128), ('qinv', 'Coefficient', 128)]


print('''/* GENERATED by tools/gen_pkg_keys.py - do not edit.
 *
 * Provenance: these are the PUBLICLY KNOWN test/"fake" RSA-2048 keysets from the
 * open-source LibOrbisPkg project (LibOrbisPkg/Util/Keys.cs: FakeKeyset and
 * PkgDerivedKey3Keyset). They are used by homebrew "fake" PKG tooling and carry
 * no console secrets. Byte order: big-endian, fixed width (left zero padded);
 * field mapping p=Prime1 q=Prime2 dp=Exponent1 dq=Exponent2 qinv=Coefficient.
 */
#ifndef WUP_PKG_KEYS_H
#define WUP_PKG_KEYS_H
#include <stdint.h>

typedef struct {
    uint8_t n[256], p[128], q[128], dp[128], dq[128], qinv[128];
} pkg_rsa_keyset_t;
''')
for label, var in (('fake', 'FakeKeyset'), ('derived3', 'PkgDerivedKey3Keyset')):
    ks = ns[var]
    print('/* %s */' % var)
    print('static const pkg_rsa_keyset_t pkg_keyset_%s = {' % label)
    for f, src, w in FIELDS:
        b = ks[src].rjust(w, b'\0')
        assert len(b) == w, (var, src, len(b))
        rows = ', '.join('0x%02x' % x for x in b)
        print('    { %s },' % rows)
    print('};\n')
print('#endif')
